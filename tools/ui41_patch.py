"""The witch hat is the dearest item, the halo a step below. On top of ui40_patch."""
import subprocess
S = '/tmp/claude-0/-home-user-rollmodel/5c52352e-692f-5301-ac55-ec4d2c708f3e/scratchpad'
subprocess.run(['python3', '-I', S + '/tools/ui40_patch.py'], check=True)
DST = '/home/claude/paint-the-canvas.html'
s = open(DST).read(); n0 = len(s)
def rep(old, new, count=1):
    global s
    c = s.count(old); assert c == count, f'expected {count}, found {c}: {old[:90]!r}'
    s = s.replace(old, new)
rep("pirate: 820, hat: 1000, halo: 1300 };", "pirate: 820, halo: 1000, hat: 1300 };")
rep('<p class="ver">Version 110</p>', '<p class="ver">Version 111</p>')
